HEADER = """// Generated by tests/generator_fuzz.py (seed {seed}). The expected values were computed in Python
// from docs/formats.md and the EIP-712 specification, never from the generator.
use core::bytes::PackedBytes
use codec_compact::Compact
use fe_codec_cbor::Cbor
use fe_codec_core::{{BoundedBuffer, CodecResult, Deserialize, ErrorKind, Format, List, Map, Schema, Serialize, Text}}
use fe_codec_eip712::Eip712Struct
use fe_codec_json::Json
use std::evm::Address
{modules}
/// Encodes, decodes the encoding and encodes the result again; the two encodings must agree.
fn stable<T: Serialize + Deserialize, F: Format, const N: usize>(_ format: F, _ value: T) {{
    let first = format.encode<T, N>(value).unwrap()
    let decoded = format.decode<T, N>(first).unwrap()
    let second = format.encode<T, N>(decoded).unwrap()
    assert!(first.equals(second))
}}
"""


# `fe test` on the EVM (sonatina) backend compiles all the tests it runs into ONE contract and
# deploys it in one transaction. Fe 26.7.0 fails that deployment with `CreateContractSizeLimit`
# (or, for a still larger contract, `create initcode size limit`) when the code is too large.
# Measured with `fe test --report` (runtime.bin): the limit is not EIP-170's 24576 bytes, since
# suites of 340 to 990 KB deploy and run, and a suite of 1.2 MB (150 tests) does not. A seed with 90 to 250 tests (2 KB to 90 KB of
# code each) is over the limit about half the time. The harness therefore runs the tests in batches of
# at most MAX_BATCH_TESTS = 16 tests (the tests of one generated type are never split, so a batch
# is larger when one type has more), selected by the name prefix `b<N>__` (`fe test --filter`
# matches a substring of the function name). The cost of a test depends on the types it uses and
# varies from 2 KB to 90 KB (a batch of 22 tests of one large type came to 1.1 MB and failed), so
# a batch that still fails with either of those errors is run again in parts, one per kind of
# test (`b<N>__json_`, `b<N>__cbor_`, ...). Every test still runs on both backends, and the
# harness checks that the runs together ran exactly as many tests as were generated. The native
# backend has no such limit and runs everything in one go.
MAX_BATCH_TESTS = 16


def hex_list(data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append(", ".join("0x%02x" % b for b in data[i:i + 16]))
    return "[" + ",\n    ".join(rows) + "]" if len(rows) > 1 else "[" + rows[0] + "]"


def int_lit(v, signed, bits):
    if signed and v < 0:
        if v == -(1 << (bits - 1)):
            return "(-0x%x - 1)" % ((1 << (bits - 1)) - 1)
        return "(-%s)" % (str(-v) if -v < (1 << 32) else "0x%x" % -v)
    return str(v) if v < (1 << 32) else "0x%x" % v


def byte_array(data):
    return "[" + ", ".join("0x%02x" % b for b in data) + "]"


def val_expr(spec, t, v, helpers):
    """The Fe expression for the value `v` of type `t`. A map is built by a function of its own
    that inserts the entries in the order given, which `helpers` collects."""
    k = t[0]
    if k == "int":
        return int_lit(v, t[1], t[2])
    if k == "bool":
        return "true" if v else "false"
    if k == "addr":
        return "Address::new(0x%s)" % v.hex()
    if k == "text":
        return "Text<%d>::from_array(%s).unwrap()" % (t[1], byte_array(v.encode()))
    if k == "buf":
        if not v:
            return "BoundedBuffer<%d>::empty()" % t[1]
        return "BoundedBuffer<%d>::from_prefix(%s).unwrap()" % (t[1], byte_array(v))
    if k == "packed":
        return "PackedBytes<%d>::from_array(%s)" % (t[1], byte_array(v))
    if k == "opt":
        return "Option::None" if v is None else "Option::Some(%s)" % val_expr(spec, t[1], v, helpers)
    if k == "arr":
        return "[" + ", ".join(val_expr(spec, t[1], x, helpers) for x in v) + "]"
    if k == "list":
        return "%s::from_array([%s]).unwrap()" % (fe_type(t), ", ".join(val_expr(spec, t[1], x, helpers) for x in v))
    if k == "map":
        name = "mkmap_%d" % len(helpers)
        slot = len(helpers)
        helpers.append(None)  # the name is taken before the entries' own helpers are
        lines = ["fn %s() -> %s {" % (name, fe_type(t)), "    var m = %s::new()" % fe_type(t)]
        for key, x in v:
            lines.append("    assert!(m.insert(%s, %s).unwrap().is_none())" % (
                val_expr(spec, t[1], key, helpers), val_expr(spec, t[2], x, helpers)))
        helpers[slot] = "\n".join(lines + ["    m", "}"])
        return name + "()"
    if k == "tup":
        return "(" + ", ".join(val_expr(spec, e, x, helpers) for e, x in zip(t[1], v)) + ("," if len(v) == 1 else "") + ")"
    m = spec.model(t[1])
    if not m.is_record:
        if not isinstance(v, Var):
            return "%s::%s" % (t[1], v)
        variant = find_variant(m, v.name)
        if variant.kind == "tuple":
            return "%s::%s(%s)" % (t[1], v.name, ", ".join(val_expr(spec, et, x, helpers)
                                                           for et, x in tuple_parts(variant, v.payload)))
        fields = ", ".join("%s: %s" % (name, val_expr(spec, ft, v.payload[name], helpers))
                           for name, ft, _ in variant_fields(variant))
        return "%s::%s { %s }" % (t[1], v.name, fields) if fields else "%s::%s {}" % (t[1], v.name)
    fields = ", ".join("%s: %s" % (name, val_expr(spec, ft, v[name], helpers)) for name, ft, _ in instance_fields(spec, t))
    return "%s { %s }" % (fe_type(t), fields) if fields else "%s {}" % fe_type(t)


def compact_bound(spec, t, v):
    """An upper bound on the compact encoding of `v` (the format's own sizes are generous here:
    it is only a buffer capacity)."""
    k = t[0]
    if k == "int":
        return t[2] // 8 + 1
    if k == "bool":
        return 2
    if k in ("addr", "packed"):
        return len(v) + 2
    if k == "text":
        return len(v.encode()) + 3
    if k == "buf":
        return len(v) + 3
    if k == "opt":
        return 2 + (compact_bound(spec, t[1], v) if v is not None else 0)
    if k == "arr":
        return 2 + sum(compact_bound(spec, t[1], x) for x in v)
    if k == "list":
        return 4 + sum(compact_bound(spec, t[1], x) for x in v)
    if k == "map":
        return 4 + sum(compact_bound(spec, t[1], key) + compact_bound(spec, t[2], x) for key, x in v)
    if k == "tup":
        return 2 + sum(compact_bound(spec, e, x) for e, x in zip(t[1], v))
    m = spec.model(t[1])
    if not m.is_record:
        if not isinstance(v, Var):
            return 12
        variant = find_variant(m, v.name)
        if variant.kind == "tuple":
            return 14 + sum(compact_bound(spec, et, x) for et, x in tuple_parts(variant, v.payload))
        return 14 + sum(compact_bound(spec, ft, v.payload[name]) for name, ft, _ in variant_fields(variant))
    return 2 + sum(compact_bound(spec, ft, v[name]) for name, ft, _ in instance_fields(spec, t))


class Builder:
    def __init__(self, spec, rng, seed):
        self.spec = spec
        self.rng = rng
        self.seed = seed
        self.consts = []
        self.fns = []
        self.helpers = []  # the functions that build maps, see val_expr
        self.features = collections.Counter()  # what the values exercised, for the coverage report
        self.count = 0
        self.stats = {"values": 0, "tests": 0}
        self.skipped_json = self.skipped_cbor = False  # unknown fields were added to some input
        self.eip_values = {}  # (struct name, value index) -> value, for debugging a failure

    def const(self, name, data):
        self.consts.append("const %s: [u8; %d] = %s" % (name, len(data), hex_list(data)))

    def test(self, name, body):
        self.fns.append("#[test]\nfn %s() {\n%s\n}" % (name, "\n".join("    " + l if l else l for l in body.split("\n"))))
        self.stats["tests"] += 1

    def targets(self):
        out = []
        for m in self.spec.models:
            if not m.generics:
                out.append(("ref", m.name, ()))
        out.extend(instances(self.spec))
        return out

    def build(self):
        """The source of the test module. `self.batches` lists the name prefixes (`b0__`, `b1__`,
        ...) that split its tests into groups of at most MAX_BATCH_TESTS; the harness runs one
        `fe test --filter <prefix>` per group (see MAX_BATCH_TESTS for why)."""
        spec = self.spec
        bounds = []  # the number of tests before each chunk, then the total
        for ti, t in enumerate(self.targets()):
            bounds.append(self.stats["tests"])
            self.target(ti, t)
        bounds.append(self.stats["tests"])
        self.rejection_tests()
        self.eip712_tests()
        self.tuple_eip712_tests()
        self.map_eip712_tests()
        self.payload_eip712_tests()
        bounds.append(self.stats["tests"])
        # Group adjacent chunks (one per generated type, then the EIP-712 tests) into batches.
        batch_of = {}  # test index -> batch
        batch, in_batch = 0, 0
        for lo, hi in zip(bounds, bounds[1:]):
            if in_batch and in_batch + (hi - lo) > MAX_BATCH_TESTS:
                batch, in_batch = batch + 1, 0
            for i in range(lo, hi):
                batch_of[i] = batch
            in_batch += hi - lo
        self.batches = ["b%d__" % i for i in range(batch + 1)]
        # For each batch, the prefixes of its tests by kind (`b3__json_`, `b3__cbor_`, ...), which
        # split it again when its code is still too large.
        self.kinds = {prefix: [] for prefix in self.batches}
        index = 0
        for k, fn in enumerate(self.fns):
            if fn.startswith("#[test]\nfn "):
                name = fn[len("#[test]\nfn "):]
                prefix = "b%d__" % batch_of[index]
                self.fns[k] = "#[test]\nfn " + prefix + name
                word = name.split("(")[0].split("_")[0]
                kind = prefix + word + ("_" if "_" in name.split("(")[0] else "")
                if kind not in self.kinds[prefix]:
                    self.kinds[prefix].append(kind)
                index += 1
        mods = "".join("use ingot::%s::*\n" % chr(ord("a") + i) for i in range(spec.modules))
        header = HEADER.format(seed=self.seed, modules=mods)
        return header + "\n" + "\n".join(self.consts) + "\n\n" + "\n\n".join(self.fns + self.helpers) + "\n"

    def target(self, ti, t):
        spec, rng = self.spec, self.rng
        ty = fe_type(t)
        m = spec.model(t[1])
        self.schema_test(ti, t)
        for vi in range(rng.choice([2, 3])):
            v = gen_value(spec, rng, t)
            self.stats["values"] += 1
            tag = "%d_%d" % (ti, vi)
            self.fns.append("fn mk_%s() -> %s {\n    %s\n}" % (tag, ty, val_expr(spec, t, v, self.helpers)))
            jb = json_bytes(spec, t, v)
            cb = cbor_bytes(spec, t, v)
            self.const("J_" + tag, jb)
            self.const("C_" + tag, cb)
            jn, cn = len(jb), len(cb)
            self.test("json_" + tag, """let expected = BoundedBuffer<%d>::from_array(J_%s)
let encoded = Json::new().encode<%s, %d>(mk_%s()).unwrap()
assert!(encoded.equals(expected))
let back: %s = Json::new().decode<%s, %d>(expected).unwrap()
assert!(Json::new().encode<%s, %d>(back).unwrap().equals(expected))""" % (jn, tag, ty, jn, tag, ty, ty, jn, ty, jn))
            self.test("cbor_" + tag, """let expected = BoundedBuffer<%d>::from_array(C_%s)
let encoded = Cbor::new().encode<%s, %d>(mk_%s()).unwrap()
assert!(encoded.equals(expected))
let back: %s = Cbor::new().decode<%s, %d>(expected).unwrap()
assert!(Cbor::new().encode<%s, %d>(back).unwrap().equals(expected))""" % (cn, tag, ty, cn, tag, ty, ty, cn, ty, cn))
            bound = compact_bound(spec, t, v) + 8
            maps = maps_in(spec, t, v)
            payloads = payload_variants_in(spec, t, v)
            if maps or payloads:
                # The compact example has no maps and no variants with a payload: writing one, even an
                # empty map, is Unsupported.
                if maps:
                    self.features["test: compact rejects maps"] += 1
                if payloads:
                    self.features["test: compact rejects payload variants"] += 1
                self.test("compact_" + tag, """match Compact::new().encode<%s, %d>(mk_%s()) {
    Result::Ok(_) => assert!(false),
    Result::Err(error) => assert!(error.kind == ErrorKind::Unsupported),
}""" % (ty, bound, tag))
            elif payload_enum_units_in(spec, t, v):
                # A variant with no payload still writes as in any enum, but the format cannot read an
                # enum that has others with one, not even that variant.
                self.features["test: compact cannot read payload enums"] += 1
                self.test("compact_" + tag, """let written = Compact::new().encode<%s, %d>(mk_%s()).unwrap()
match Compact::new().decode<%s, %d>(written) {
    Result::Ok(_) => assert!(false),
    Result::Err(error) => assert!(error.kind == ErrorKind::Unsupported),
}""" % (ty, bound, tag, ty, bound))
            else:
                self.test("compact_" + tag, "stable<%s, Compact, %d>(Compact::new(), mk_%s())" % (ty, bound, tag))
            self.count_variants(t, v)
            for mt, pairs in maps:
                if len(pairs) > 1:
                    self.features["map: entries inserted out of key order"] += 1
                if not pairs:
                    self.features["map: empty value"] += 1
                if pairs and len(pairs) == mt[3]:
                    self.features["map: full to capacity"] += 1
            # JSON the decoder must accept, in another shape: the same value comes back.
            for k in range(rng.choice([1, 2])):
                added = [0, 0]
                text = noisy_json(spec, rng, t, v, added=added).encode()
                if added[0]:
                    self.skipped_json = True
                if added[1]:
                    self.features["skip: unknown JSON members in a record variant"] += 1
                name = "S_%s_%d" % (tag, k)
                self.const(name, text)
                n = len(text)
                self.test("shuffled_%s_%d" % (tag, k), """let input = BoundedBuffer<%d>::from_array(%s)
let back: %s = Json::new().decode<%s, %d>(input).unwrap()
assert!(Json::new().encode<%s, %d>(back).unwrap().equals(BoundedBuffer<%d>::from_array(J_%s)))
let again: %s = Json::new().decode<%s, %d>(input).unwrap()
assert!(Cbor::new().encode<%s, %d>(again).unwrap().equals(BoundedBuffer<%d>::from_array(C_%s)))"""
                          % (n, name, ty, ty, n, ty, jn, jn, tag, ty, ty, n, ty, cn, cn, tag))
            # CBOR with fields the reader does not know, where a record is marked to skip them.
            added = [0, 0]
            extended = reference.cbor(to_cbor_with_unknown(spec, rng, t, v, added))
            if added[0]:
                self.skipped_cbor = True
                if added[1]:
                    self.features["skip: unknown CBOR fields in a record variant"] += 1
                name = "X_" + tag
                self.const(name, extended)
                xn = len(extended)
                self.test("skipped_cbor_" + tag, """let input = BoundedBuffer<%d>::from_array(%s)
let back: %s = Cbor::new().decode<%s, %d>(input).unwrap()
assert!(Cbor::new().encode<%s, %d>(back).unwrap().equals(BoundedBuffer<%d>::from_array(C_%s)))"""
                          % (xn, name, ty, ty, xn, ty, cn, cn, tag))
            self.field_tests(tag, t, v, jn)

    def count_variants(self, t, v):
        """Coverage of what the value `v` holds."""
        for nt, nv in nodes(self.spec, t, v):
            if nt[0] == "ref" and isinstance(nv, Var):
                variant = find_variant(self.spec.model(nt[1]), nv.name)
                if variant.kind == "record" and any(ft[0] == "opt" and nv.payload[name] is None
                                                    for name, ft, _ in variant_fields(variant)):
                    self.features["enum: optional field left out of a record variant"] += 1

    def rejection_tests(self):
        """What a decoder must say to a variant written in the wrong form (docs/formats.md,
        "Enums with payloads"), for each enum that has a payload, read as the root."""
        spec, rng = self.spec, self.rng
        for ti, t in enumerate(self.targets()):
            m = spec.model(t[1])
            if m.is_record or not m.has_payload:
                continue
            ty = fe_type(t)
            calls = {"json": [], "cbor": []}
            count = [0]
            inputs = []

            def call(fmt, data, kind, offset):
                name = "R_%d_%d" % (ti, count[0])
                count[0] += 1
                self.const(name, data)
                inputs.append(len(data))
                calls[fmt].append("%sfails_%d(%s, ErrorKind::%s, %d)" % (fmt[0], ti, name, kind, offset))

            for variant in m.variants:
                name = variant.name
                if variant.kind == "unit":
                    # A wrapper where a name stands.
                    self.features["test: unit variant written as a wrapper is rejected"] += 1
                    call("json", ('{"%s":null}' % name).encode(), "TypeMismatch", 0)
                    call("cbor", bytes([0xa1]) + reference.cbor(variant.id) + b"\xf6", "TypeMismatch", 0)
                    continue
                # A name where a wrapper stands.
                self.features["test: payload variant written bare is rejected"] += 1
                call("json", ('"%s"' % name).encode(), "TypeMismatch", 0)
                call("cbor", reference.cbor(variant.id), "TypeMismatch", 0)
                # A wrapper of two entries: the whole of the first is read before the second is seen.
                v = gen_variant(spec, rng, variant)
                full = json_bytes(spec, t, v)
                first = full[:-1]
                self.features["test: wrapper of two entries is rejected"] += 1
                call("json", first + b"," + full[1:], "InvalidLength", len(first))
                cb = cbor_bytes(spec, t, v)
                call("cbor", bytes([0xa2]) + cb[1:] + cb[1:], "InvalidLength", 0)
            self.features["test: wrapper of no entry is rejected"] += 1
            call("json", b"{}", "InvalidLength", 1)
            call("cbor", b"\xa0", "InvalidLength", 0)
            capacity = max(inputs)
            for fmt, label in (("json", "Json"), ("cbor", "Cbor")):
                self.helpers.append("""fn %sfails_%d<const N: usize>(_ input: [u8; N], _ kind: ErrorKind, _ offset: usize) {
    match %s::new().decode<%s, %d>(BoundedBuffer<%d>::from_prefix(input).unwrap()) {
        Result::Ok(_) => assert!(false),
        Result::Err(error) => {
            assert!(error.kind == kind)
            assert!(error.offset == offset)
        },
    }
}""" % (fmt[0], ti, label, ty, capacity, capacity))
                self.test("rejects_%s_%d" % (fmt, ti), "\n".join(calls[fmt]))

    def field_tests(self, tag, t, v, jn):
        spec, rng = self.spec, self.rng
        required, optional = [], []
        in_maps = set()
        variants = set()
        for occ, fields, rv, is_variant in record_occurrences(spec, t, v, in_maps=in_maps):
            if is_variant:
                variants.add(occ)
            for name, ft, _ in fields:
                if ft[0] == "opt":
                    if rv[name] is not None:
                        optional.append((occ, name))
                else:
                    required.append((occ, name))
        ty = fe_type(t)

        def pick(fields, feature):
            """A field to leave out, more often one inside the value of a map, or of a record variant,
            when there is one."""
            inside = [f for f in fields if f[0] in in_maps]
            of_variants = [f for f in fields if f[0] in variants]
            chosen = rng.choice(inside if inside and rng.random() < 0.6 else
                                of_variants if of_variants and rng.random() < 0.6 else fields)
            if chosen[0] in in_maps:
                self.features["map: field left out inside a map value"] += 1
            if chosen[0] in variants:
                self.features[feature] += 1
            return chosen

        if required:
            occ, name = pick(required, "test: required field missing from a record variant")
            text = noisy_json(spec, rng, t, v, drop=(occ, name)).encode()
            n = len(text)
            cname = "M_" + tag
            self.const(cname, text)
            raw = name.encode()
            self.test("missing_" + tag, """let input = BoundedBuffer<%d>::from_array(%s)
match Json::new().decode<%s, %d>(input) {
    Result::Ok(_) => assert!(false),
    Result::Err(error) => {
        assert!(error.kind == ErrorKind::MissingField)
        assert!(error.field().unwrap().as_bytes().equals(BoundedBuffer<%d>::from_array(%s)))
    },
}""" % (n, cname, ty, n, len(raw), byte_array(raw)))
        if optional:
            occ, name = pick(optional, "test: optional field dropped from a record variant")
            text = noisy_json(spec, rng, t, v, drop=(occ, name)).encode()
            n = len(text)
            expected = json_bytes(spec, t, dropped_value(spec, t, v, occ, name))
            cname, ename = "D_" + tag, "E_" + tag
            self.const(cname, text)
            self.const(ename, expected)
            en = len(expected)
            self.test("dropped_" + tag, """let input = BoundedBuffer<%d>::from_array(%s)
let back: %s = Json::new().decode<%s, %d>(input).unwrap()
assert!(Json::new().encode<%s, %d>(back).unwrap().equals(BoundedBuffer<%d>::from_array(%s)))"""
                      % (n, cname, ty, ty, n, ty, en, en, ename))

    def schema_test(self, ti, t):
        spec = self.spec
        m = spec.model(t[1])
        ty = fe_type(t)

        def name_check(expr, name):
            raw = name.encode()
            return "assert!(%s.as_bytes().equals(BoundedBuffer<%d>::from_array(%s)))" % (expr, len(raw), byte_array(raw))

        lines = [name_check("<%s as Schema>::name()" % ty, m.name)]
        if m.is_record:
            fields = instance_fields(spec, t)
            for i, (name, ft, fid) in enumerate(fields):
                lines.append("let f%d = <%s as Schema>::field(%d).unwrap()" % (i, ty, i))
                lines.append(name_check("f%d.name" % i, name))
                lines.append("assert!(f%d.id == %d)" % (i, fid))
                lines.append("assert!(f%d.optional == %s)" % (i, "true" if ft[0] == "opt" else "false"))
            lines.append("assert!(<%s as Schema>::field(%d).is_none())" % (ty, len(fields)))
            lines.append("assert!(<%s as Schema>::variant(0).is_none())" % ty)
            lines.append("assert!(%s<%s as Schema>::skips_unknown_fields())" % ("" if m.skip_unknown else "!", ty))
        else:
            for i, v in enumerate(m.variants):
                lines.append("let v%d = <%s as Schema>::variant(%d).unwrap()" % (i, ty, i))
                lines.append(name_check("v%d.name" % i, v.name))
                lines.append("assert!(v%d.id == %d)" % (i, v.id))
            lines.append("assert!(<%s as Schema>::variant(%d).is_none())" % (ty, len(m.variants)))
            lines.append("assert!(<%s as Schema>::field(0).is_none())" % ty)
            lines.append("assert!(!<%s as Schema>::skips_unknown_fields())" % ty)
        self.test("schema_%d" % ti, "\n".join(lines))

    def tuple_eip712_tests(self):
        """EIP-712 has no tuples: the generic path must fail for a record that reaches one."""
        for ti, t in enumerate(self.targets()):
            if self.spec.model(t[1]).is_record and self.reaches_tuple(t):
                self.test("eip712_rejects_tuples_%d" % ti, "assert!(fe_codec_eip712::type_hash<%s>().is_err())" % fe_type(t))

    def map_eip712_tests(self):
        """EIP-712 has no maps either: the generic path must fail for a record that reaches one."""
        for ti, t in enumerate(self.targets()):
            if self.spec.model(t[1]).is_record and self.reaches(t, "map"):
                self.features["test: maps have no EIP-712 form"] += 1
                self.test("eip712_rejects_maps_%d" % ti, "assert!(fe_codec_eip712::type_hash<%s>().is_err())" % fe_type(t))

    def payload_eip712_tests(self):
        """EIP-712 has no union types: the generic path must fail for a record that reaches an enum with
        a payload."""
        for ti, t in enumerate(self.targets()):
            if self.spec.model(t[1]).is_record and self.reaches(t, "enum with payloads"):
                self.features["test: payload enums have no EIP-712 form"] += 1
                self.test("eip712_rejects_enums_%d" % ti, "assert!(fe_codec_eip712::type_hash<%s>().is_err())" % fe_type(t))

    def reaches_tuple(self, t):
        return self.reaches(t, "tup")

    def reaches(self, t, kind):
        """Whether the type `t` is or contains a `kind` of type ('enum with payloads' is an enum with a
        variant that has one), through the fields of the records and the payloads of the variants it
        names."""
        for w in walk(t):
            if w[0] == kind:
                return True
            if w[0] == "ref":
                m = self.spec.model(w[1])
                if kind == "enum with payloads" and not m.is_record and m.has_payload:
                    return True
                env = {g[1]: a for g, a in zip(m.generics, w[2])}
                inner = [f.ty for f in m.fields] if m.is_record else m.payload_types()
                if any(self.reaches(subst(ty, env), kind) for ty in inner):
                    return True
        return False

