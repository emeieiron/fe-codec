use std::fmt::Write;

use crate::schema::{Field, Schema, Shape, ValueType, Variant};

pub const HEADER: &str = "// Generated by fe-codec-gen. Do not edit.\n";

pub fn render(schema: &Schema, module: &str) -> String {
    let mut out = String::from(HEADER);
    if schema.nodes.iter().any(|ty| {
        matches!(
            ty,
            ValueType::Integer {
                bits: 8 | 16 | 32,
                ..
            }
        )
    }) {
        out.push_str("use core::num::IntDowncast\n");
    }
    out.push_str(
        "use fe_codec_core::{\n\
         \x20   CodecError, CodecResult, Decoder, Encoder, ErrorKind, FieldDescriptor, SerialDescriptor,\n\
         \x20   SerialKind, Serializer, Text, TypeDescriptor, VariantDescriptor, schema_name,\n\
         }\n",
    );
    writeln!(out, "use ingot::{module} as model_types").unwrap();
    describe_nodes(&mut out, schema, module);
    describe_members(&mut out, schema);
    for (name, shape) in &schema.models {
        render_model(&mut out, schema, name, shape);
    }
    for (index, ty) in schema.nodes.iter().enumerate() {
        if let ValueType::Array(element, length) = ty {
            render_array(&mut out, schema, index, ty, element, *length);
        }
    }
    out
}

fn name_literal(name: &str) -> String {
    format!(r#"schema_name<{}>("{}")"#, name.len(), name)
}

fn describe_nodes(out: &mut String, schema: &Schema, module: &str) {
    writeln!(
        out,
        "\nfn schema_node(_ index: usize) -> Option<TypeDescriptor> {{"
    )
    .unwrap();
    writeln!(out, "    match index {{").unwrap();
    for (index, ty) in schema.nodes.iter().enumerate() {
        let (name, kind, count, element) = match ty {
            ValueType::Bool => ("bool".into(), "Bool".into(), 0, None),
            ValueType::Integer { signed, bits } => {
                let kind = if *signed { "Signed" } else { "Unsigned" };
                (ty.fe(), format!("{kind}({bits})"), 0, None)
            }
            ValueType::Text(capacity) => ("Text".into(), format!("Text({capacity})"), 0, None),
            ValueType::Array(element, length) => (
                "array".into(),
                "Sequence".into(),
                *length,
                Some(schema.index(element)),
            ),
            ValueType::Named(name) => {
                let (kind, count) = match &schema.models[name] {
                    Shape::Record(fields) => ("Record", fields.len()),
                    Shape::Enum(variants) => ("UnitEnum", variants.len()),
                };
                (format!("{module}::{name}"), kind.into(), count, None)
            }
        };
        let name = name_literal(&name);
        let element = element.map_or("Option::None".into(), |index| {
            format!("Option::Some({index})")
        });
        writeln!(out,
            "        {index} => Option::Some(TypeDescriptor {{ name: {name}, kind: SerialKind::{kind}, count: {count}, element: {element} }}),"
        ).unwrap();
    }
    out.push_str("        _ => Option::None,\n    }\n}\n");
}

fn describe_members(out: &mut String, schema: &Schema) {
    out.push_str("\nfn schema_field(_ node: usize, _ index: usize) -> Option<FieldDescriptor> {\n    match (node, index) {\n");
    for (name, shape) in &schema.models {
        if let Shape::Record(fields) = shape {
            let node = schema.model_index(name);
            for (index, field) in fields.iter().enumerate() {
                let name = name_literal(&field.name);
                let id = field.id.unwrap_or(index as u64 + 1);
                let optional = field.optional;
                let value_node = schema.index(&field.ty);
                writeln!(out,
                    "        ({node}, {index}) => Option::Some(FieldDescriptor {{ name: {name}, index: {index}, id: {id}, optional: {optional}, value_node: {value_node} }}),"
                ).unwrap();
            }
        }
    }
    out.push_str("        _ => Option::None,\n    }\n}\n");

    out.push_str("\nfn schema_variant(_ node: usize, _ index: usize) -> Option<VariantDescriptor> {\n    match (node, index) {\n");
    for (name, shape) in &schema.models {
        if let Shape::Enum(variants) = shape {
            let node = schema.model_index(name);
            for (index, variant) in variants.iter().enumerate() {
                let name = name_literal(&variant.name);
                let id = variant.id.unwrap_or(index as u64);
                writeln!(out,
                    "        ({node}, {index}) => Option::Some(VariantDescriptor {{ name: {name}, index: {index}, id: {id} }}),"
                ).unwrap();
            }
        }
    }
    out.push_str("        _ => Option::None,\n    }\n}\n");
}

fn render_model(out: &mut String, schema: &Schema, name: &str, shape: &Shape) {
    let node = schema.model_index(name);
    let model = format!("model_types::{name}");
    writeln!(out, "\npub struct {name}Serializer {{}}\n").unwrap();
    writeln!(out, "impl SerialDescriptor for {name}Serializer {{").unwrap();
    writeln!(out, "    fn root() -> usize {{ {node} }}").unwrap();
    out.push_str("    fn node(_ index: usize) -> Option<TypeDescriptor> { schema_node(index) }\n");
    out.push_str("    fn field(_ node: usize, _ index: usize) -> Option<FieldDescriptor> { schema_field(node, index) }\n");
    out.push_str("    fn variant(_ node: usize, _ index: usize) -> Option<VariantDescriptor> { schema_variant(node, index) }\n}\n");

    writeln!(out, "\nimpl Serializer<{model}> for {name}Serializer {{").unwrap();
    writeln!(
        out,
        "    fn encode<E: Encoder>(_ value: {model}, _ encoder: mut E) -> CodecResult<()> {{"
    )
    .unwrap();
    match shape {
        Shape::Record(fields) => encode_record(out, schema, fields, node),
        Shape::Enum(variants) => encode_enum(out, &model, variants, node),
    }
    writeln!(out, "    }}\n").unwrap();
    writeln!(
        out,
        "    fn decode<D: Decoder>(_ decoder: mut D) -> CodecResult<{model}> {{"
    )
    .unwrap();
    match shape {
        Shape::Record(fields) => decode_record(out, schema, &model, fields, node),
        Shape::Enum(variants) => decode_enum(out, &model, variants, node),
    }
    out.push_str("    }\n}\n");
}

fn encode_record(out: &mut String, schema: &Schema, fields: &[Field], node: usize) {
    let required = fields.iter().filter(|field| !field.optional).count();
    if required == fields.len() {
        writeln!(out, "        let count: usize = {required}").unwrap();
    } else {
        writeln!(out, "        var count: usize = {required}").unwrap();
        for field in fields.iter().filter(|field| field.optional) {
            writeln!(
                out,
                "        if value.{}.is_some() {{ count += 1 }}",
                field.name
            )
            .unwrap();
        }
    }
    writeln!(
        out,
        "        var record = encoder.begin_record<Self>({node}, count)?"
    )
    .unwrap();
    let declared: Vec<_> = fields.iter().enumerate().collect();
    let mut sorted = declared.clone();
    sorted.sort_by_key(|(index, field)| field.id.unwrap_or(*index as u64 + 1));
    if sorted
        .iter()
        .map(|(index, _)| index)
        .eq(declared.iter().map(|(index, _)| index))
    {
        encode_fields(out, schema, &declared, node, "        ");
    } else {
        out.push_str("        if E::RECORD_FIELDS_BY_ID {\n");
        encode_fields(out, schema, &sorted, node, "            ");
        out.push_str("        } else {\n");
        encode_fields(out, schema, &declared, node, "            ");
        out.push_str("        }\n");
    }
    out.push_str("        encoder.end_record(record)\n");
}

fn encode_fields(
    out: &mut String,
    schema: &Schema,
    fields: &[(usize, &Field)],
    node: usize,
    indent: &str,
) {
    for (index, field) in fields {
        let body;
        let (inner, value) = if field.optional {
            writeln!(
                out,
                "{indent}if let Option::Some(ref field_value) = value.{} {{",
                field.name
            )
            .unwrap();
            body = format!("{indent}    ");
            (body.as_str(), "field_value".into())
        } else {
            (indent, format!("value.{}", field.name))
        };
        writeln!(
            out,
            "{inner}encoder.field(mut record, schema_field({node}, {index}).unwrap())?"
        )
        .unwrap();
        writeln!(out, "{inner}{}?", encode_value(schema, &field.ty, &value)).unwrap();
        if field.optional {
            writeln!(out, "{indent}}}").unwrap();
        }
    }
}

fn decode_record(out: &mut String, schema: &Schema, model: &str, fields: &[Field], node: usize) {
    for (index, field) in fields.iter().enumerate() {
        let ty = field.ty.fe();
        let ty = if field.optional {
            format!("Option<{ty}>")
        } else {
            ty
        };
        writeln!(
            out,
            "        var field_{index}: Option<{ty}> = Option::None"
        )
        .unwrap();
    }
    writeln!(
        out,
        "        var record = decoder.begin_record<Self>({node})?"
    )
    .unwrap();
    writeln!(
        out,
        "        while let Option::Some(field) = decoder.next_field<Self>({node}, mut record)? {{"
    )
    .unwrap();
    out.push_str("            match field.index {\n");
    for (index, field) in fields.iter().enumerate() {
        writeln!(out, "                {index} => {{").unwrap();
        writeln!(out, "                    if field_{index}.is_some() {{").unwrap();
        writeln!(out, "                        return Result::Err(CodecError::at(kind: ErrorKind::DuplicateField, offset: field.offset).at_field({node}, {index}))\n                    }}").unwrap();
        let value = decode_value(schema, &field.ty);
        if field.optional {
            out.push_str("                    let value = if decoder.take_null()? {\n                        Option::None\n                    } else {\n");
            writeln!(out, "                        Option::Some({value})").unwrap();
            out.push_str("                    }\n");
        } else {
            writeln!(out, "                    let value = {value}").unwrap();
        }
        writeln!(
            out,
            "                    field_{index} = Option::Some(value)\n                }},"
        )
        .unwrap();
    }
    out.push_str("                _ => return Result::Err(CodecError::at(kind: ErrorKind::UnknownField, offset: field.offset)),\n            }\n        }\n");
    out.push_str("        decoder.end_record(record)?\n");
    for (index, field) in fields.iter().enumerate() {
        writeln!(out, "        let value_{index} = match field_{index} {{").unwrap();
        out.push_str("            Option::Some(value) => value,\n");
        let fallback = if field.optional {
            "Option::None".to_string()
        } else {
            format!(
                "return Result::Err(CodecError::at(kind: ErrorKind::MissingField, offset: decoder.offset()).at_field({node}, {index}))"
            )
        };
        writeln!(out, "            Option::None => {fallback},\n        }}").unwrap();
    }
    writeln!(out, "        Result::Ok({model} {{").unwrap();
    for (index, field) in fields.iter().enumerate() {
        writeln!(out, "            {}: value_{index},", field.name).unwrap();
    }
    out.push_str("        })\n");
}

fn encode_enum(out: &mut String, model: &str, variants: &[Variant], node: usize) {
    out.push_str("        let index: usize = match value {\n");
    for (index, variant) in variants.iter().enumerate() {
        let variant = &variant.name;
        writeln!(out, "            {model}::{variant} => {index},").unwrap();
    }
    writeln!(out, "        }}\n        encoder.write_variant<Self>({node}, schema_variant({node}, index).unwrap())").unwrap();
}

fn decode_enum(out: &mut String, model: &str, variants: &[Variant], node: usize) {
    writeln!(
        out,
        "        let start = decoder.offset()\n        match decoder.read_variant<Self>({node})? {{"
    )
    .unwrap();
    for (index, variant) in variants.iter().enumerate() {
        let variant = &variant.name;
        writeln!(
            out,
            "            {index} => Result::Ok({model}::{variant}),"
        )
        .unwrap();
    }
    out.push_str("            _ => Result::Err(CodecError::at(kind: ErrorKind::UnknownVariant, offset: start)),\n        }\n");
}

fn render_array(
    out: &mut String,
    schema: &Schema,
    node: usize,
    array: &ValueType,
    element: &ValueType,
    length: usize,
) {
    let ty = array.fe();
    writeln!(out, "\nfn encode_array_{node}<E: Encoder>(_ value: {ty}, _ encoder: mut E) -> CodecResult<()> {{").unwrap();
    writeln!(out, "    var sequence = encoder.begin_sequence({length})?").unwrap();
    if length != 0 {
        writeln!(
            out,
            "    var index: usize = 0\n    while index < {length} {{"
        )
        .unwrap();
        out.push_str("        encoder.element(mut sequence)?\n");
        writeln!(
            out,
            "        {}?",
            encode_value(schema, element, "value[index]")
        )
        .unwrap();
        out.push_str("        index += 1\n    }\n");
    }
    out.push_str("    encoder.end_sequence(sequence)\n}\n");

    writeln!(
        out,
        "\nfn decode_array_{node}<D: Decoder>(_ decoder: mut D) -> CodecResult<{ty}> {{"
    )
    .unwrap();
    writeln!(out, "    var sequence = decoder.begin_sequence({length})?").unwrap();
    for index in 0..length {
        out.push_str("    decoder.element(mut sequence)?\n");
        writeln!(
            out,
            "    let item_{index} = {}",
            decode_value(schema, element)
        )
        .unwrap();
    }
    out.push_str("    decoder.end_sequence(sequence)?\n");
    let elements = (0..length)
        .map(|index| format!("item_{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(out, "    Result::Ok([{elements}])\n}}").unwrap();
}

fn encode_value(schema: &Schema, ty: &ValueType, value: &str) -> String {
    match ty {
        ValueType::Bool => format!("encoder.write_bool({value})"),
        ValueType::Integer { signed, bits } => {
            let (method, width) = if *signed {
                ("signed", "i64")
            } else {
                ("unsigned", "u64")
            };
            let value = if *bits == 64 {
                value.to_owned()
            } else {
                format!("{value} as {width}")
            };
            format!("encoder.write_{method}({value}, {bits})")
        }
        ValueType::Text(capacity) => format!("encoder.write_text<{capacity}>({value})"),
        ValueType::Named(name) => format!("{name}Serializer::encode({value}, mut encoder)"),
        ValueType::Array(_, _) => {
            format!("encode_array_{}({value}, mut encoder)", schema.index(ty))
        }
    }
}

fn decode_value(schema: &Schema, ty: &ValueType) -> String {
    match ty {
        ValueType::Bool => "decoder.read_bool()?".into(),
        ValueType::Integer { signed, bits } => {
            let method = if *signed { "signed" } else { "unsigned" };
            let suffix = if *bits == 64 {
                ""
            } else {
                ".downcast_unchecked()"
            };
            format!("decoder.read_{method}({bits})?{suffix}")
        }
        ValueType::Text(capacity) => format!("decoder.read_text<{capacity}>()?"),
        ValueType::Named(name) => format!("{name}Serializer::decode(mut decoder)?"),
        ValueType::Array(_, _) => format!("decode_array_{}(mut decoder)?", schema.index(ty)),
    }
}
