//! Renders `Schema`, `Serialize` and `Deserialize` impls as ordinary Fe source.
//!
//! The output has the shape a handwritten impl would have, uses only the public
//! `fe_codec_core` API, and depends on nothing but its inputs, so the same sources always
//! produce the same bytes.

use std::fmt::Write;

use crate::schema::{Field, Generic, Model, Output, Shape, Variant};

pub const HEADER: &str = "// Generated by fe-codec-gen. Do not edit.\n";

const CORE: &str = "fe_codec_core";

/// The generated module's imports: everything its sources declare and import, so field
/// types resolve as they do there.
pub fn imports(out: &mut String, output: &Output) {
    for module in &output.modules {
        writeln!(out, "use ingot::{module}::*").unwrap();
    }
    for item in &output.uses {
        writeln!(out, "{item}").unwrap();
    }
}

pub fn render(output: &Output) -> String {
    let mut out = String::from(HEADER);
    imports(&mut out, output);
    writeln!(out, "use {CORE}::{{Serialize as _, Deserialize as _}}").unwrap();
    let mut helpers = 0;
    for model in &output.models {
        match &model.shape {
            Shape::Record(fields) => render_record(&mut out, model, fields, &mut helpers),
            Shape::Enum(variants) => render_enum(&mut out, model, variants),
        }
    }
    out
}

/// `<T: bound + ..., const N: usize>` with `extra` added to each type parameter's bounds.
fn parameters(model: &Model, extra: &dyn Fn(&str) -> Vec<String>) -> String {
    if model.generics.is_empty() {
        return String::new();
    }
    let parts: Vec<String> = model
        .generics
        .iter()
        .map(|generic| match generic {
            Generic::Type { name, bounds } => {
                let mut all = extra(name);
                all.extend(bounds.clone());
                if all.is_empty() {
                    name.clone()
                } else {
                    format!("{name}: {}", all.join(" + "))
                }
            }
            Generic::Const { name, ty } => format!("const {name}: {ty}"),
        })
        .collect();
    format!("<{}>", parts.join(", "))
}

fn self_type(model: &Model) -> String {
    if model.generics.is_empty() {
        return model.name.clone();
    }
    let names: Vec<_> = model.generics.iter().map(Generic::name).collect();
    format!("{}<{}>", model.name, names.join(", "))
}

fn name_literal(name: &str) -> String {
    format!(r#"{CORE}::schema_name<{}>("{}")"#, name.len(), name)
}

fn serialize_bounds(_: &str) -> Vec<String> {
    vec![format!("{CORE}::Serialize")]
}

fn deserialize_bounds(model: &Model) -> impl Fn(&str) -> Vec<String> + '_ {
    move |name| {
        let mut bounds = vec![format!("{CORE}::Deserialize")];
        if model.copy_params.contains(name) {
            bounds.push("Copy".into());
        }
        bounds
    }
}

fn render_record(out: &mut String, model: &Model, fields: &[Field], helpers: &mut usize) {
    let ty = self_type(model);

    // Schema: fields by ascending ID.
    writeln!(
        out,
        "\nimpl{} {CORE}::Schema for {ty} {{",
        parameters(model, &|_| Vec::new())
    )
    .unwrap();
    render_name(out, &model.name);
    writeln!(
        out,
        "    fn field(_ position: usize) -> Option<{CORE}::FieldInfo> {{"
    )
    .unwrap();
    if fields.is_empty() {
        out.push_str("        Option::None\n");
    } else {
        out.push_str("        match position {\n");
        for (position, field) in fields.iter().enumerate() {
            writeln!(
                out,
                "            {position} => Option::Some({CORE}::FieldInfo {{ name: {}, id: {}, optional: {} }}),",
                name_literal(&field.name),
                field.id,
                field.optional,
            )
            .unwrap();
        }
        out.push_str("            _ => Option::None,\n        }\n");
    }
    out.push_str("    }\n}\n");

    // Serialize: visit present fields in position order.
    writeln!(
        out,
        "\nimpl{} {CORE}::Serialize for {ty} {{",
        parameters(model, &serialize_bounds)
    )
    .unwrap();
    writeln!(
        out,
        "    fn serialize<CodecEncoder: {CORE}::Encoder>(self, _ encoder: mut CodecEncoder) -> {CORE}::CodecResult<()> {{"
    )
    .unwrap();
    let required = fields.iter().filter(|field| !field.optional).count();
    if required == fields.len() {
        writeln!(out, "        let present: usize = {required}").unwrap();
    } else {
        writeln!(out, "        var present: usize = {required}").unwrap();
        for field in fields.iter().filter(|field| field.optional) {
            writeln!(
                out,
                "        if !CodecEncoder::OMIT_NONE || self.{}.is_some() {{\n            present += 1\n        }}",
                field.name
            )
            .unwrap();
        }
    }
    out.push_str("        var record = encoder.begin_record<Self>(present)?\n");
    for (position, field) in fields.iter().enumerate() {
        let visit = format!(
            "encoder.field<Self>(mut record, {position})?\n{{indent}}self.{}.serialize(mut encoder)?\n",
            field.name
        );
        if field.optional {
            writeln!(
                out,
                "        if !CodecEncoder::OMIT_NONE || self.{}.is_some() {{",
                field.name
            )
            .unwrap();
            out.push_str("            ");
            out.push_str(&visit.replace("{indent}", "            "));
            out.push_str("        }\n");
        } else {
            out.push_str("        ");
            out.push_str(&visit.replace("{indent}", "        "));
        }
    }
    out.push_str("        encoder.end_record(record)\n    }\n}\n");

    // Deserialize: collect each field once, then require the non-optional ones.
    let bounds = deserialize_bounds(model);
    let mut unrolled = Vec::new();
    writeln!(
        out,
        "\nimpl{} {CORE}::Deserialize for {ty} {{",
        parameters(model, &bounds)
    )
    .unwrap();
    writeln!(
        out,
        "    fn deserialize<CodecDecoder: {CORE}::Decoder>(_ decoder: mut CodecDecoder) -> {CORE}::CodecResult<Self> {{"
    )
    .unwrap();
    for (position, field) in fields.iter().enumerate() {
        writeln!(
            out,
            "        var field_{position}: Option<{}> = Option::None",
            field.ty
        )
        .unwrap();
    }
    out.push_str("        var record = decoder.begin_record<Self>()?\n");
    out.push_str("        while let Option::Some(key) = decoder.next_field<Self>(mut record)? {\n");
    out.push_str("            match key.position {\n");
    for (position, field) in fields.iter().enumerate() {
        match &field.unrolled {
            None => writeln!(
                out,
                "                {position} => key.read(mut decoder, mut field_{position})?,"
            )
            .unwrap(),
            Some((element, length)) => {
                let helper = format!("decode_array_{helpers}");
                *helpers += 1;
                let arguments: Vec<_> = model
                    .generics
                    .iter()
                    .map(|generic| generic.name().to_string())
                    .chain(["CodecDecoder".to_string()])
                    .collect();
                writeln!(out, "                {position} => {{").unwrap();
                writeln!(out, "                    if field_{position}.is_some() {{").unwrap();
                writeln!(
                    out,
                    "                        return Result::Err({CORE}::CodecError::at(kind: {CORE}::ErrorKind::DuplicateField, offset: key.offset).in_field(key.name))"
                )
                .unwrap();
                out.push_str("                    }\n");
                writeln!(
                    out,
                    "                    field_{position} = match {helper}<{}>(mut decoder) {{",
                    arguments.join(", ")
                )
                .unwrap();
                out.push_str("                        Result::Ok(value) => Option::Some(value),\n");
                out.push_str(
                    "                        Result::Err(error) => return Result::Err(error.in_field(key.name)),\n",
                );
                out.push_str("                    }\n                },\n");
                unrolled.push((helper, element.clone(), *length));
            }
        }
    }
    out.push_str("                _ => return Result::Err(key.unknown()),\n");
    out.push_str("            }\n        }\n");
    out.push_str("        decoder.end_record(record)?\n");
    out.push_str("        Result::Ok(Self {\n");
    for (position, field) in fields.iter().enumerate() {
        if field.optional {
            writeln!(
                out,
                "            {}: {CORE}::optional(field_{position}),",
                field.name
            )
            .unwrap();
        } else {
            writeln!(
                out,
                "            {}: <Self as {CORE}::Schema>::required(field_{position}, {position}, decoder.offset())?,",
                field.name
            )
            .unwrap();
        }
    }
    out.push_str("        })\n    }\n}\n");

    for (helper, element, length) in unrolled {
        render_unrolled(out, model, &helper, &element, length);
    }

    // Describe: the record and each field's type, in position order.
    writeln!(
        out,
        "\nimpl{} {CORE}::Describe for {ty} {{",
        parameters(model, &describe_bounds)
    )
    .unwrap();
    render_describe_header(out);
    out.push_str("        describer.begin_record<Self>()?\n");
    for (position, field) in fields.iter().enumerate() {
        writeln!(out, "        describer.field<Self>({position})?").unwrap();
        writeln!(
            out,
            "        <{} as {CORE}::Describe>::describe(mut describer)?",
            field.ty
        )
        .unwrap();
    }
    out.push_str("        describer.end_record<Self>()\n    }\n}\n");
}

fn describe_bounds(_: &str) -> Vec<String> {
    vec![format!("{CORE}::Describe")]
}

fn render_describe_header(out: &mut String) {
    writeln!(
        out,
        "    fn describe<CodecDescriber: {CORE}::Describer>(_ describer: mut CodecDescriber) -> {CORE}::CodecResult<()> {{"
    )
    .unwrap();
}

fn render_name(out: &mut String, name: &str) {
    writeln!(
        out,
        "    fn name() -> {CORE}::SchemaName {{ {} }}",
        name_literal(name)
    )
    .unwrap();
}

/// Decodes a literal-length array element by element, so its elements need not be `Copy`.
fn render_unrolled(out: &mut String, model: &Model, helper: &str, element: &str, length: usize) {
    let bounds = deserialize_bounds(model);
    let mut generics = parameters(model, &bounds);
    let decoder = format!("CodecDecoder: {CORE}::Decoder");
    generics = if generics.is_empty() {
        format!("<{decoder}>")
    } else {
        format!("{}, {decoder}>", &generics[..generics.len() - 1])
    };
    writeln!(
        out,
        "\nfn {helper}{generics}(_ decoder: mut CodecDecoder) -> {CORE}::CodecResult<[{element}; {length}]> {{"
    )
    .unwrap();
    writeln!(out, "    var sequence = decoder.begin_sequence({length})?").unwrap();
    for index in 0..length {
        out.push_str("    decoder.element(mut sequence)?\n");
        writeln!(
            out,
            "    let item_{index} = <{element} as {CORE}::Deserialize>::deserialize(mut decoder)?"
        )
        .unwrap();
    }
    out.push_str("    decoder.end_sequence(sequence)?\n");
    let items: Vec<_> = (0..length).map(|index| format!("item_{index}")).collect();
    writeln!(out, "    Result::Ok([{}])\n}}", items.join(", ")).unwrap();
}

fn render_enum(out: &mut String, model: &Model, variants: &[Variant]) {
    let ty = &model.name;
    writeln!(out, "\nimpl {CORE}::Schema for {ty} {{").unwrap();
    render_name(out, ty);
    writeln!(
        out,
        "    fn variant(_ index: usize) -> Option<{CORE}::VariantInfo> {{"
    )
    .unwrap();
    out.push_str("        match index {\n");
    for (index, variant) in variants.iter().enumerate() {
        writeln!(
            out,
            "            {index} => Option::Some({CORE}::VariantInfo {{ name: {}, id: {} }}),",
            name_literal(&variant.name),
            variant.id
        )
        .unwrap();
    }
    out.push_str("            _ => Option::None,\n        }\n    }\n}\n");

    writeln!(out, "\nimpl {CORE}::Serialize for {ty} {{").unwrap();
    writeln!(
        out,
        "    fn serialize<CodecEncoder: {CORE}::Encoder>(self, _ encoder: mut CodecEncoder) -> {CORE}::CodecResult<()> {{"
    )
    .unwrap();
    out.push_str("        let index: usize = match self {\n");
    for (index, variant) in variants.iter().enumerate() {
        writeln!(out, "            {ty}::{} => {index},", variant.name).unwrap();
    }
    out.push_str("        }\n        encoder.write_variant<Self>(index)\n    }\n}\n");

    writeln!(out, "\nimpl {CORE}::Deserialize for {ty} {{").unwrap();
    writeln!(
        out,
        "    fn deserialize<CodecDecoder: {CORE}::Decoder>(_ decoder: mut CodecDecoder) -> {CORE}::CodecResult<Self> {{"
    )
    .unwrap();
    out.push_str("        let start = decoder.offset()\n");
    out.push_str("        match decoder.read_variant<Self>()? {\n");
    for (index, variant) in variants.iter().enumerate() {
        writeln!(
            out,
            "            {index} => Result::Ok({ty}::{}),",
            variant.name
        )
        .unwrap();
    }
    writeln!(
        out,
        "            _ => Result::Err({CORE}::CodecError::at(kind: {CORE}::ErrorKind::UnknownVariant, offset: start)),"
    )
    .unwrap();
    out.push_str("        }\n    }\n}\n");

    writeln!(out, "\nimpl {CORE}::Describe for {ty} {{").unwrap();
    render_describe_header(out);
    out.push_str("        describer.enumeration<Self>()\n    }\n}\n");
}
