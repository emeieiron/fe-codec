use std::fs;
use std::path::PathBuf;
use std::process::{Command, Output};

struct Ingot {
    _dir: tempfile::TempDir,
    src: PathBuf,
    source: PathBuf,
    output: PathBuf,
}

impl Ingot {
    fn new(source: &str) -> Self {
        let dir = tempfile::tempdir().unwrap();
        let src = dir.path().join("src");
        fs::create_dir(&src).unwrap();
        fs::write(dir.path().join("fe.toml"), "[ingot]\nname = \"test_models\"\n").unwrap();
        let source_path = src.join("models.fe");
        fs::write(&source_path, source).unwrap();
        Self {
            _dir: dir,
            output: src.join("serializers.fe"),
            source: source_path,
            src,
        }
    }

    fn command(&self, sources: &[&PathBuf]) -> Command {
        let mut command = Command::new(env!("CARGO_BIN_EXE_fe-codec-gen"));
        for source in sources {
            command.arg("--source").arg(source);
        }
        command
    }

    fn generate(&self, check: bool) -> Output {
        let mut command = self.command(&[&self.source]);
        command.arg("--out").arg(&self.output);
        if check {
            command.arg("--check");
        }
        command.output().unwrap()
    }

    fn generated(&self) -> String {
        fs::read_to_string(&self.output).unwrap()
    }
}

fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

fn success(output: Output) {
    assert!(output.status.success(), "{}", stderr(&output));
}

#[test]
fn generates_impls_for_serializable_items_only_and_deterministically() {
    let ingot = Ingot::new(
        r#"
        use fe_codec_core::Text

        #[serializable]
        pub struct Batch { pub children: [Item; 0x02] }
        #[serializable]
        pub struct Item {
            pub kind: Kind,
            pub label: Option<Text<8>>,
        }
        #[serializable]
        pub enum Kind { First, Second }
        pub struct Ignored { private: usize }
        "#,
    );
    success(ingot.generate(false));
    let first = ingot.generated();
    for ty in ["Batch", "Item", "Kind"] {
        assert!(first.contains(&format!("impl fe_codec_core::Serialize for {ty} {{")));
        assert!(first.contains(&format!("impl fe_codec_core::Deserialize for {ty} {{")));
        assert!(first.contains(&format!("impl fe_codec_core::Schema for {ty} {{")));
    }
    assert!(!first.contains("Ignored"));
    assert!(first.contains(r#"    fn name() -> fe_codec_core::SchemaName { fe_codec_core::schema_name<4>("Item") }"#));
    assert!(first.contains("impl fe_codec_core::Describe for Kind {"));
    assert!(first.contains("        describer.enumeration<Self>()"));
    assert!(first.contains(
        "        describer.field<Self>(0)?\n        <[Item; 0x02] as fe_codec_core::Describe>::describe(mut describer)?"
    ));
    assert!(first.starts_with("// Generated by fe-codec-gen. Do not edit.\nuse ingot::models::*\nuse fe_codec_core::Text\n"));
    assert!(!first.contains("fe_codec_json") && !first.contains("fe_codec_cbor"));
    // `Item` is not Copy, so its array is decoded element by element.
    assert!(first.contains("fn decode_array_0<CodecDecoder: fe_codec_core::Decoder>"));
    assert!(first.contains("-> fe_codec_core::CodecResult<[Item; 2]>"));

    success(ingot.generate(true));
    success(ingot.generate(false));
    assert_eq!(first, ingot.generated());
}

#[test]
fn fields_are_listed_and_visited_in_ascending_id_order() {
    let ingot = Ingot::new(
        "#[serializable]\npub struct Item {\n    #[codec_id = 9]\n    pub late: u8,\n    #[codec_id = 2]\n    pub early: u8,\n}\n",
    );
    success(ingot.generate(false));
    let generated = ingot.generated();
    assert!(generated.contains(
        r#"0 => Option::Some(fe_codec_core::FieldInfo { name: fe_codec_core::schema_name<5>("early"), id: 2, optional: false }),"#
    ));
    assert!(generated.contains(
        r#"1 => Option::Some(fe_codec_core::FieldInfo { name: fe_codec_core::schema_name<4>("late"), id: 9, optional: false }),"#
    ));
    let early = generated.find("self.early.serialize").unwrap();
    let late = generated.find("self.late.serialize").unwrap();
    assert!(early < late);
}

#[test]
fn generic_records_bound_their_parameters() {
    let ingot = Ingot::new(
        "#[serializable]\npub struct Page<T, const N: usize> { pub items: [T; N], pub next: Option<u64> }\n\
         #[serializable]\npub struct Pair<A: Copy, B> { pub left: A, pub right: B }\n",
    );
    success(ingot.generate(false));
    let generated = ingot.generated();
    assert!(generated.contains("impl<T, const N: usize> fe_codec_core::Schema for Page<T, N> {"));
    assert!(generated.contains("impl<T: fe_codec_core::Serialize, const N: usize> fe_codec_core::Serialize for Page<T, N> {"));
    assert!(generated.contains(
        "impl<T: fe_codec_core::Deserialize + Copy, const N: usize> fe_codec_core::Deserialize for Page<T, N> {"
    ));
    assert!(generated.contains(
        "impl<A: fe_codec_core::Deserialize + Copy, B: fe_codec_core::Deserialize> fe_codec_core::Deserialize for Pair<A, B> {"
    ));
    assert!(generated.contains(
        "impl<T: fe_codec_core::Describe, const N: usize> fe_codec_core::Describe for Page<T, N> {"
    ));
}

#[test]
fn copy_elements_use_the_generic_array_impl() {
    let ingot = Ingot::new(
        "#[serializable]\npub struct Item { pub id: u8 }\nimpl Copy for Item {}\n\
         #[serializable]\npub struct Batch { pub items: [Item; 2], pub empty: [u8; 0], pub bytes: [u8; 100] }\n",
    );
    success(ingot.generate(false));
    let generated = ingot.generated();
    // Only the empty array needs a helper.
    assert_eq!(generated.matches("fn decode_array_").count(), 1);
    assert!(generated.contains("-> fe_codec_core::CodecResult<[u8; 0]>"));
}

#[test]
fn several_sources_share_one_output() {
    let ingot = Ingot::new("#[serializable]\npub struct Item { pub id: u8 }\n");
    let other = ingot.src.join("records.fe");
    fs::write(&other, "use ingot::models::Item\n\n#[serializable]\npub struct Holder { pub item: Item }\n").unwrap();
    let output = ingot
        .command(&[&ingot.source, &other])
        .arg("--out")
        .arg(&ingot.output)
        .output()
        .unwrap();
    success(output);
    let generated = ingot.generated();
    assert!(generated.contains("use ingot::models::*\nuse ingot::records::*\nuse ingot::models::Item\n"));
    assert!(generated.contains("impl fe_codec_core::Serialize for Holder {"));
}

#[test]
fn check_detects_missing_and_stale_output_without_writing() {
    let ingot = Ingot::new("#[serializable]\npub struct Item { pub id: u8 }\n");
    let missing = ingot.generate(true);
    assert!(!missing.status.success());
    assert!(stderr(&missing).contains("error: generated serializers are missing or stale"));
    assert!(!ingot.output.exists());

    success(ingot.generate(false));
    let old = ingot.generated();
    fs::write(&ingot.source, "#[serializable]\npub struct Item { pub id: u16 }\n").unwrap();
    let stale = ingot.generate(true);
    assert!(!stale.status.success());
    assert!(stderr(&stale).contains("missing or stale"));
    assert_eq!(old, ingot.generated());

    success(ingot.generate(false));
    assert_ne!(old, ingot.generated());
    success(ingot.generate(true));
}

#[test]
fn unsupported_declarations_report_locations_and_preserve_generated_output() {
    let ingot = Ingot::new("#[serializable]\npub struct Item { pub id: u8 }\n");
    success(ingot.generate(false));
    let original = ingot.generated();
    let cases = [
        ("#[serializable]\npub struct Item {\n    pub id: usize\n}\n", "different width on each target"),
        ("#[serializable]\npub struct Item {\n    pub id: Option<Option<u8>>\n}\n", "cannot round-trip"),
        ("#[serializable]\npub struct Item {\n    id: u8\n}\n", "must be `pub` or `pub(ingot)`"),
        ("#[serializable]\npub struct Item {\n    pub child: Plain\n}\npub struct Plain { pub id: u8 }\n", "'Plain' is used by 'Item' but is not #[serializable]"),
        ("#[serializable]\npub enum Item {\n    Variant(u8)\n}\n", "only unit enum variants"),
        ("#[serializable]\npub struct Item {\n    pub ids: [Child; 65]\n}\n#[serializable]\npub struct Child { pub id: u8 }\n", "implement Copy for the element type"),
        ("#[serializable]\npub struct Item {\n    pub ids: Option<[Child; 2]>\n}\n#[serializable]\npub struct Child { pub id: u8 }\n", "implement Copy for the element type"),
        ("#[serializable]\npub struct Item {\n    #[codec_ids = 1]\n    pub id: u8\n}\n", "unknown codec attribute 'codec_ids'"),
        ("#[serializable]\npub struct Item<T>\n    where T: Copy { pub id: T }\n", "where clauses"),
        ("#[serializable]\npub struct Item<T = u8> {\n    pub id: T\n}\n", "without defaults"),
        ("#[serializable(all)]\npub struct Item {\n    pub id: u8\n}\n", "takes no arguments"),
        ("#[serializable]\npub struct Item {\n    pub a_field_name_of_thirty_two_bytes: u8\n}\n", "schema name exceeds 31 bytes"),
    ];
    for (source, message) in cases {
        fs::write(&ingot.source, source).unwrap();
        let output = ingot.generate(false);
        assert!(!output.status.success(), "accepted: {source}");
        let error = stderr(&output);
        assert!(error.contains("models.fe:") && error.contains(": error: "), "{error}");
        assert!(error.contains(message), "{error}");
        assert_eq!(original, ingot.generated());
    }
}

