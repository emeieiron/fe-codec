#[test]
fn malformed_source_and_handwritten_destinations_are_left_intact() {
    let ingot = Ingot::new("#[serializable]\npub struct Item { pub id: u8 }\n");
    let handwritten = "// Handwritten\npub fn manual() {}\n";
    fs::write(&ingot.output, handwritten).unwrap();

    let output = ingot.generate(false);
    assert!(!output.status.success());
    assert!(stderr(&output).contains("error: refusing to replace handwritten source"));
    assert_eq!(handwritten, ingot.generated());

    fs::write(&ingot.source, "#[serializable]\npub struct Item {\n    pub id:\n").unwrap();
    let output = ingot.generate(false);
    assert!(!output.status.success());
    assert!(stderr(&output).contains("models.fe:"));
    assert_eq!(handwritten, ingot.generated());
}

#[test]
fn stdout_produces_the_same_source_without_writing_files() {
    let ingot = Ingot::new("#[serializable]\npub struct Item { pub id: u8 }\n");
    let first = ingot.command(&[&ingot.source]).arg("--stdout").output().unwrap();
    assert!(first.status.success(), "{}", stderr(&first));
    assert!(first.stderr.is_empty());
    let entries: Vec<_> = fs::read_dir(&ingot.src).unwrap().collect();
    assert_eq!(entries.len(), 1, "--stdout must not write files");

    let second = ingot.command(&[&ingot.source]).arg("--stdout").output().unwrap();
    assert_eq!(first.stdout, second.stdout, "output must be deterministic");

    success(ingot.generate(false));
    assert_eq!(first.stdout, fs::read(&ingot.output).unwrap());
}

#[test]
fn rejects_incomplete_duplicate_and_zero_ids() {
    for (members, expected) in [
        ("#[codec_id = 7]\npub a: u8,\npub b: u8", "every member"),
        ("#[codec_id = 7]\npub a: u8,\n#[codec_id = 7]\npub b: u8", "duplicate codec_id"),
        ("#[codec_id = 0]\npub a: u8", "must be positive"),
    ] {
        let ingot = Ingot::new(&format!("#[serializable]\npub struct Item {{\n{members}\n}}\n"));
        let result = ingot.generate(false);
        assert!(!result.status.success());
        assert!(stderr(&result).contains(expected), "{}", stderr(&result));
    }
}

fn eip712(ingot: &Ingot) -> Output {
    ingot.command(&[&ingot.source]).args(["--eip712", "--stdout"]).output().unwrap()
}

#[test]
fn eip712_mode_emits_compile_time_type_hashes_and_static_hashing() {
    let ingot = Ingot::new(
        "use fe_codec_core::Text\nuse std::evm::Address\n\n\
         #[serializable]\npub struct Person { pub name: Text<16>, pub wallet: Address }\n\
         #[serializable]\n#[eip712]\npub struct Mail { pub from: Person, pub to: Person, pub contents: Text<32>, pub level: Level, pub tags: [u8; 2] }\n\
         #[serializable]\npub enum Level { Low, High }\n\
         #[serializable]\npub struct Unsigned { pub note: Option<u8> }\n",
    );
    let first = eip712(&ingot);
    assert!(first.status.success(), "{}", stderr(&first));
    let generated = String::from_utf8(first.stdout.clone()).unwrap();
    assert!(generated.contains(
        r#"    const TYPE_HASH: u256 = core::keccak("Mail(Person from,Person to,string contents,uint8 level,uint8[2] tags)Person(string name,address wallet)")"#
    ));
    assert!(generated.contains(r#"core::keccak("Person(string name,address wallet)")"#));
    assert!(generated.contains("            <Person as fe_codec_eip712::Eip712Member>::member(self.from),"));
    assert!(generated.contains("            Level::High => 1,"));
    // Only #[eip712] structs and what they use; types EIP-712 cannot express may share the file.
    assert!(!generated.contains("Unsigned"));
    assert!(!generated.contains("fe_codec_core::Serialize"));
    assert_eq!(first.stdout, eip712(&ingot).stdout, "output must be deterministic");
}

#[test]
fn eip712_mode_reports_types_it_cannot_express() {
    let cases = [
        ("#[serializable]\n#[eip712]\npub struct Item {\n    pub note: Option<u8>\n}\n", "EIP-712 has no optional types"),
        ("#[serializable]\n#[eip712]\npub struct Item<T> {\n    pub value: T\n}\n", "is generic"),
        ("use core::bytes::PackedBytes\n#[serializable]\n#[eip712]\npub struct Item {\n    pub data: PackedBytes<33>\n}\n", "from 1 to 32"),
        ("#[serializable]\n#[eip712]\npub struct Item {\n    pub rank: Rank\n}\n#[serializable]\npub enum Rank {\n    #[codec_id = 0]\n    Low,\n    #[codec_id = 300]\n    High,\n}\n", "variant 'High' has ID 300"),
        ("use ingot::other::Celsius\n#[serializable]\n#[eip712]\npub struct Item {\n    pub temperature: Celsius\n}\n", "cannot see type 'Celsius'"),
        ("#[eip712]\npub struct Item {\n    pub id: u8\n}\n#[serializable]\npub struct Other { pub id: u8 }\n", "must also be #[serializable]"),
        ("#[serializable]\npub struct Item { pub id: u8 }\n", "no #[eip712] struct found"),
    ];
    for (source, message) in cases {
        let ingot = Ingot::new(source);
        let output = eip712(&ingot);
        assert!(!output.status.success(), "accepted: {source}");
        let error = stderr(&output);
        assert!(error.contains("models.fe:") && error.contains(": error: "), "{error}");
        assert!(error.contains(message), "{error}");
    }
}
